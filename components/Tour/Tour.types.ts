/** Where a step scrolls the page before (or while) it speaks. */
export interface TourScroll {
  /** Element to scroll to. */
  target: string;
  /** `start` lands the element's top under the nav; `through` scrolls from its
   *  top to its bottom while the line plays, so a pinned scene runs like video. */
  mode: "start" | "through";
}

/** What the pretend cursor does in a step. */
export interface TourPointer {
  /** Element to glide to (its centre). Omitted: the cursor drifts mid-screen. */
  target?: string;
  /** Press it once it arrives. */
  click?: boolean;
}

export interface TourStep {
  /** Message key under `Tour.steps`. */
  id: string;
  /** Element the spotlight frames while the line plays. Omitted for scene
   *  scrolls, where the whole screen is the subject. */
  focus?: string;
  scroll?: TourScroll;
  pointer?: TourPointer;
  /** Runs after the line has played — e.g. closes the popup a click opened. */
  after?: "closeDialog";
}

export type TourStatus = "idle" | "playing" | "paused";

/** One spoken word: start and length (ms) in the audio, and the caption
 *  characters [s, e) it covers. Generated by `scripts/generate-tour-audio.py`. */
export interface TourWord {
  t: number;
  d: number;
  s: number;
  e: number;
}

export interface TourLineTiming {
  /** Length of the narration (ms). */
  duration: number;
  words: TourWord[];
}


export interface TourCaptionProps {
  line: string;
  /** How many caption characters the voice has said — read every frame. */
  getProgress: () => number;
  index: number;
  total: number;
  paused: boolean;
  labels: { pause: string; resume: string; close: string };
  onToggle: () => void;
  onClose: () => void;
}
